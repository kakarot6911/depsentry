"""Generate a labelled benchmark of synthetic Python projects.

Why synthetic: reachability ground truth is the thing being measured, and no
public corpus labels "is the vulnerable symbol actually called". Generating the
projects means the label is known by construction rather than assumed.

For every (project, advisory) pair the generator decides whether to emit code
that calls the vulnerable symbol or a safe alternative, and writes that decision
to ground_truth.json. Metrics in experiments/evaluate.py are computed against
those labels.

The generator is seeded, so the corpus -- and therefore every number in the
results chapter -- is reproducible.
"""

from __future__ import annotations

import json
import random
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from depsentry.vulndb import DEFAULT_DB, VulnerabilityDB  # noqa: E402

BENCHMARK_DIR = Path(__file__).resolve().parents[1] / "benchmark"

# Import name and a safe alternative call for each distribution we generate.
PACKAGE_PROFILES: dict[str, dict[str, str]] = {
    "requests":     {"import": "requests",     "safe": "requests.head(url)"},
    "urllib3":      {"import": "urllib3",      "safe": "urllib3.util.parse_url(url)"},
    "jinja2":       {"import": "jinja2",       "safe": "jinja2.escape(text)"},
    "pyyaml":       {"import": "yaml",         "safe": "yaml.safe_load(stream)"},
    "pillow":       {"import": "PIL",          "safe": "PIL.Image.new('RGB', (8, 8))"},
    "cryptography": {"import": "cryptography", "safe": "cryptography.fernet.Fernet.generate_key()"},
    "flask":        {"import": "flask",        "safe": "flask.jsonify(payload)"},
    "werkzeug":     {"import": "werkzeug",     "safe": "werkzeug.utils.secure_filename(name)"},
    "numpy":        {"import": "numpy",        "safe": "numpy.array(values)"},
    "pandas":       {"import": "pandas",       "safe": "pandas.read_csv(path)"},
    "sqlalchemy":   {"import": "sqlalchemy",   "safe": "sqlalchemy.select(table)"},
    "joblib":       {"import": "joblib",       "safe": "joblib.hash(obj)"},
    "click":        {"import": "click",        "safe": "click.style(text)"},
    "pydantic":     {"import": "pydantic",     "safe": "pydantic.TypeAdapter(int)"},
    "certifi":      {"import": "certifi",      "safe": "certifi.contents()"},
    "idna":         {"import": "idna",         "safe": "idna.check_label(label)"},
}

PROJECT_KINDS = ("web_api", "data_pipeline", "cli_tool", "batch_worker")

_HEADER = '"""Synthetic benchmark project generated by make_benchmark.py."""\n\n'


def _call_expression(symbol: str) -> str:
    """Render a syntactically valid call to a dotted symbol."""
    return f"{symbol}(payload)"


def _module_for_symbol(symbol: str) -> str:
    """Top-level import needed to make `symbol` resolvable."""
    return symbol.split(".", 1)[0]


def _write_project(
    project_dir: Path,
    kind: str,
    packages: list[str],
    reachable_symbols: list[str],
    unreachable_symbols: list[str],
) -> None:
    project_dir.mkdir(parents=True, exist_ok=True)

    # requirements.txt pins deliberately vulnerable versions so the advisory
    # matcher has something to find; reachability is the variable under test.
    pins = {
        "requests": "2.28.0", "urllib3": "1.26.5", "jinja2": "3.0.1",
        "pyyaml": "5.4.1", "pillow": "9.5.0", "cryptography": "40.0.1",
        "flask": "2.2.0", "werkzeug": "2.2.2", "numpy": "1.24.0",
        "pandas": "2.1.0", "sqlalchemy": "2.0.10", "joblib": "1.2.0",
        "click": "8.1.0", "pydantic": "2.5.0", "certifi": "2023.5.7",
        "idna": "3.4",
    }
    (project_dir / "requirements.txt").write_text(
        "\n".join(f"{p}=={pins.get(p, '1.0.0')}" for p in sorted(packages)) + "\n",
        encoding="utf-8",
    )

    imports = sorted({_module_for_symbol(s) for s in reachable_symbols + unreachable_symbols})
    imports += [PACKAGE_PROFILES[p]["import"] for p in packages]
    import_block = "\n".join(f"import {m}" for m in sorted(set(imports)))

    # --- core.py: helpers that ARE called from the entrypoint --------------
    reachable_body = "\n".join(
        f"    result.append({_call_expression(s)})" for s in reachable_symbols
    ) or "    pass"

    # --- dead.py: helpers that are NOT called from anywhere ----------------
    # Leading underscore keeps _mark_orphan_entrypoints from promoting them.
    unreachable_body = "\n".join(
        f"    result.append({_call_expression(s)})" for s in unreachable_symbols
    ) or "    pass"

    (project_dir / "core.py").write_text(
        _HEADER + import_block + f'''


def _process(payload):
    """Called from the entrypoint; exercises the reachable symbols."""
    result = []
{reachable_body}
    return result


def handle(payload):
    """Application entrypoint for a {kind}."""
    return _process(payload)
''',
        encoding="utf-8",
    )

    (project_dir / "dead.py").write_text(
        _HEADER + import_block + f'''


def _never_called(payload):
    """Private helper with no inbound edge: unreachable by construction."""
    result = []
{unreachable_body}
    return result
''',
        encoding="utf-8",
    )

    entry = {
        "web_api": (
            "from core import handle\n\n\n"
            "def main():\n"
            '    """HTTP entrypoint."""\n'
            "    return handle({'source': 'http'})\n"
        ),
        "data_pipeline": (
            "from core import handle\n\n\n"
            "def main():\n"
            '    """Batch entrypoint."""\n'
            "    return handle({'source': 'batch'})\n"
        ),
        "cli_tool": (
            "from core import handle\n\n\n"
            "def main():\n"
            '    """CLI entrypoint."""\n'
            "    return handle({'source': 'cli'})\n"
        ),
        "batch_worker": (
            "from core import handle\n\n\n"
            "def main():\n"
            '    """Worker entrypoint."""\n'
            "    return handle({'source': 'queue'})\n"
        ),
    }[kind]

    (project_dir / "main.py").write_text(_HEADER + entry, encoding="utf-8")


def generate(
    n_projects: int = 40,
    *,
    seed: int = 42,
    reach_rate: float = 0.35,
    db_path: Path = DEFAULT_DB,
    out_dir: Path = BENCHMARK_DIR,
) -> dict:
    """Build the corpus.

    reach_rate is the probability that a given advisory's symbol is genuinely
    called. 0.35 reflects the widely reported finding that only a minority of
    dependency CVEs sit on an executed path.
    """
    rng = random.Random(seed)

    with VulnerabilityDB(db_path) as db:
        advisories = db.all_advisories()

    by_package: dict[str, list] = {}
    for adv in advisories:
        if adv.package in PACKAGE_PROFILES:
            by_package.setdefault(adv.package, []).append(adv)

    available = sorted(by_package)
    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    ground_truth: dict[str, dict] = {}

    for i in range(n_projects):
        name = f"project_{i:03d}"
        kind = rng.choice(PROJECT_KINDS)
        packages = rng.sample(available, k=rng.randint(3, min(7, len(available))))

        reachable_symbols: list[str] = []
        unreachable_symbols: list[str] = []
        labels: dict[str, bool] = {}

        for pkg in packages:
            for adv in by_package[pkg]:
                if not adv.affected_symbols:
                    labels[adv.vuln_id] = False
                    continue

                symbol = adv.affected_symbols[0]
                # Symbols we cannot render as a plain call are skipped, not
                # mislabelled -- a wrong label would corrupt the metrics.
                if not symbol or symbol.endswith(")") or " " in symbol:
                    continue

                if rng.random() < reach_rate:
                    reachable_symbols.append(symbol)
                    labels[adv.vuln_id] = True
                else:
                    unreachable_symbols.append(symbol)
                    labels[adv.vuln_id] = False

        _write_project(
            out_dir / name, kind, packages,
            sorted(set(reachable_symbols)), sorted(set(unreachable_symbols)),
        )

        ground_truth[name] = {
            "kind": kind,
            "packages": sorted(packages),
            "exploitable": labels,
            "n_reachable": sum(1 for v in labels.values() if v),
            "n_total": len(labels),
        }

    manifest = {
        "seed": seed,
        "reach_rate": reach_rate,
        "n_projects": n_projects,
        "projects": ground_truth,
    }
    (out_dir / "ground_truth.json").write_text(
        json.dumps(manifest, indent=2), encoding="utf-8"
    )

    total = sum(p["n_total"] for p in ground_truth.values())
    reachable = sum(p["n_reachable"] for p in ground_truth.values())
    print(
        f"Generated {n_projects} projects in {out_dir}\n"
        f"  advisory instances : {total}\n"
        f"  truly reachable    : {reachable} ({reachable / max(total, 1):.1%})"
    )
    return manifest


if __name__ == "__main__":
    generate()
